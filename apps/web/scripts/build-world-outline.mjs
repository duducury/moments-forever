// Generates src/lib/geo/world-outline.ts: a tiny, simplified equirectangular outline of the continents, used only as a
// decorative background (trip-route-art.tsx). Source: public/geo/land-v1.json. Run: node scripts/build-world-outline.mjs
import { readFileSync, writeFileSync } from "node:fs";

const land = JSON.parse(readFileSync(new URL("../public/geo/land-v1.json", import.meta.url), "utf8"));
const SCALE = 2; // svg units per degree
const LAT_TOP = 78;
const LAT_BOTTOM = -57;
const TOLERANCE = 1.5; // degrees
const MIN_AREA = 16; // square degrees; drops small islands

function perpDist(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len = dx * dx + dy * dy;
  if (len === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len));
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}
function simplify(points, tol) {
  if (points.length < 3) return points;
  let max = 0;
  let idx = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpDist(points[i], points[0], points[points.length - 1]);
    if (d > max) {
      max = d;
      idx = i;
    }
  }
  if (max <= tol) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, idx + 1), tol).slice(0, -1), ...simplify(points.slice(idx), tol)];
}
function area(ring) {
  let s = 0;
  for (let i = 0; i < ring.length - 1; i++) s += ring[i][0] * ring[i + 1][1] - ring[i + 1][0] * ring[i][1];
  return Math.abs(s / 2);
}

const rings = [];
for (const f of land.features) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    const outer = poly[0];
    if (area(outer) < MIN_AREA) continue;
    if (outer.every((p) => p[1] < LAT_BOTTOM)) continue; // Antarctica
    rings.push(simplify(outer, TOLERANCE));
  }
}
const fmt = (n) => String(Math.round(n * 10) / 10);
const d = rings
  .filter((r) => r.length >= 4)
  .map((r) => "M" + r.map(([lon, lat]) => `${fmt((lon + 180) * SCALE)} ${fmt((LAT_TOP - Math.max(LAT_BOTTOM, lat)) * SCALE)}`).join("L") + "Z")
  .join("");
const w = 360 * SCALE;
const h = (LAT_TOP - LAT_BOTTOM) * SCALE;
writeFileSync(
  new URL("../src/lib/geo/world-outline.ts", import.meta.url),
  `// Generated by scripts/build-world-outline.mjs - do not edit by hand.\n// Simplified continent outlines (equirectangular), decorative only.\nexport const WORLD_OUTLINE_VIEWBOX = "0 0 ${w} ${h}";\nexport const WORLD_OUTLINE_PATH =\n  "${d}";\n`,
);
console.log("rings", rings.length, "bytes", d.length, "viewBox", w, h);
