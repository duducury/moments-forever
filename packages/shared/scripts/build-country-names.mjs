// Generates src/country-names.generated.ts: every ISO 3166-1 country with its
// display name in several languages, taken from the ICU data bundled with Node.
// Run: node packages/shared/scripts/build-country-names.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const LOCALES = ["en", "pt", "pt-PT", "es", "fr", "de", "it"];
// Codes ICU knows that are not countries (groupings, reserved, sub-territories
// of no use as "I travelled to …").
const NOT_COUNTRIES = new Set([
  "AC", "AN", "BU", "CP", "CQ", "CS", "DD", "DG", "DY", "HV", "NH", "RH", "UK", "VD", "EA", "EU", "EZ", "FX", "IC", "NT", "QO", "SU", "TA", "TP", "UN", "XA", "XB", "YD", "YU", "ZR", "ZZ",
]);

const displayNames = LOCALES.map(
  (locale) => new Intl.DisplayNames([locale], { type: "region", fallback: "none" }),
);

const countries = {};
for (let a = 65; a <= 90; a += 1) {
  for (let b = 65; b <= 90; b += 1) {
    const code = String.fromCharCode(a, b);
    if (NOT_COUNTRIES.has(code)) continue;
    const names = displayNames
      .map((formatter) => formatter.of(code))
      .filter((name) => typeof name === "string" && name !== code);
    if (names.length === 0) continue;
    countries[code] = [...new Set(names)];
  }
}

const body = Object.entries(countries)
  .map(([code, names]) => `  ${code}: ${JSON.stringify(names)},`)
  .join("\n");

const out = `// GENERATED by scripts/build-country-names.mjs — do not edit by hand.
// ${Object.keys(countries).length} ISO 3166-1 countries; names in ${LOCALES.join(", ")}.
// First name is English, second is Portuguese (pt-BR).

export const COUNTRY_NAMES_BY_ISO: Readonly<Record<string, readonly string[]>> = {
${body}
};
`;

writeFileSync(
  fileURLToPath(new URL("../src/country-names.generated.ts", import.meta.url)),
  out,
);
console.log(`${Object.keys(countries).length} countries`);
